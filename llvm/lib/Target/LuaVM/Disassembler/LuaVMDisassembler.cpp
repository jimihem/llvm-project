using namespace llvm;
using namespace support::endian;

// Helper: sign extend N-bit unsigned value to int64
static inline int64_t SignExtend64(uint64_t val, unsigned bits) {
  unsigned shift = 64 - bits;
  return (int64_t)(val << shift) >> shift;
}

LuaVMDisassembler::LuaVMDisassembler(const MCSubtargetInfo &STI, MCContext &Ctx)
    : MCDisassembler(STI, Ctx) {}

MCDisassembler::DecodeStatus
LuaVMDisassembler::getInstruction(MCInst &Instr, uint64_t &Size,
                                         ArrayRef<uint8_t> Bytes,
                                         uint64_t Address, raw_ostream &CStream) const{
  Instr.clear();
  Size = 0;
  // At least 4 bytes required for standard instruction
  if (Bytes.size() < 4)
    return MCDisassembler::Fail;

  uint32_t Ins32 = read32be(Bytes.data());
  uint8_t OpCode = (Ins32 >> 24) & 0xFF; // Extract 8-bit opcode from [31:24]

  // LIType 64bit MOVi: Op=0b00110101(0x35), occupies 8 bytes
  constexpr uint8_t OP_MOVI = 0x35;
  if (OpCode == OP_MOVI) {
    if (Bytes.size() < 8) return MCDisassembler::Fail;
    Size = 8;
    uint64_t Ins64 = read64be(Bytes.data());
    uint8_t rt = (Ins64 >> 51) & 0x1F;       // rt field [55:51], 5 bits
    uint64_t imm51 = Ins64 & ((1ULL << 51) - 1); // imm51 field [50:0], 51 bits

    // Set target opcode generated by TableGen
    Instr.setOpcode(LuaVM::MOVi);
    // Add GPR register operand for rt
    Instr.addOperand(MCOperand::createReg(getRegEnc(rt)));
    // Add 51-bit immediate operand
    Instr.addOperand(MCOperand::createImm(imm51));
    return MCDisassembler::Success;
  }

  // Regular 32-bit instruction, fixed 4-byte length
  Size = 4;
  switch(OpCode) {
  // ========== IType format: op(8),rs(5),rt(5),imm14(14) | [31-24]/[23-19]/[18-14]/[13-0]
  case 0x20: // ADDi
  case 0x21: // SUBi
  case 0x24: // MULi
  case 0x25: // DIVi
  case 0x2B: // DIViu
  case 0x2C: // ANDi
  case 0x2D: // ORi
  case 0x2E: // XORi
  case 0x2F: // NORi
  case 0x30: // CMPi
  case 0x31: // CMPiu
  case 0x32: // SHLi
  case 0x33: // SHRi
  case 0x34: // SRAi
  case 0x8A: // JIND
  case 0x87: // JALR
  case 0x88: // JSUB
  case 0x8B: // JALR_PIC
  case 0x8C: // JSUB_PIC
    {
      uint8_t rs = (Ins32 >> 19) & 0x1F;
      uint8_t rt = (Ins32 >> 14) & 0x1F;
      uint64_t imm14 = Ins32 & 0x3FFF; // Raw 14-bit immediate value
      int64_t imm14_sext = SignExtend64(imm14,14); // Sign-extend to 16-bit signed

      unsigned Op;
      switch(OpCode) {
      case 0x20: Op=LuaVM::ADDi; break;
      case 0x21: Op=LuaVM::SUBi; break;
      case 0x24: Op=LuaVM::MULi; break;
      case 0x25: Op=LuaVM::DIVi; break;
      case 0x2B: Op=LuaVM::DIViu; break;
      case 0x2C: Op=LuaVM::ANDi; break;
      case 0x2D: Op=LuaVM::ORi; break;
      case 0x2E: Op=LuaVM::XORi; break;
      case 0x2F: Op=LuaVM::NORi; break;
      case 0x30: Op=LuaVM::CMPi; break;
      case 0x31: Op=LuaVM::CMPiu; break;
      case 0x32: Op=LuaVM::SHLi; break;
      case 0x33: Op=LuaVM::SHRi; break;
      case 0x34: Op=LuaVM::SRAi; break;
      case 0x8A: Op=LuaVM::JIND; break;
      case 0x87: Op=LuaVM::JALR; break;
      case 0x88: Op=LuaVM::JSUB; break;
      case 0x8B: Op=LuaVM::JALR_PIC; break;
      case 0x8C: Op=LuaVM::JSUB_PIC; break;
      default: return MCDisassembler::Fail;
      }
      Instr.setOpcode(Op);

      // Fill operands matching InOperandList defined in td file
      if(Op==LuaVM::CMPi || Op==LuaVM::CMPiu) {
        // CMPi: input rs + imm, rt is hardcoded to zero and ignored
        Instr.addOperand(MCOperand::createReg(getRegEnc(rs)));
        Instr.addOperand(MCOperand::createImm(imm14_sext));
      } else if(Op==LuaVM::JIND || Op==LuaVM::JALR || Op==LuaVM::JALR_PIC) {
        // JIND/JALR: only rt register input, rs/imm fixed zero
        Instr.addOperand(MCOperand::createReg(getRegEnc(rt)));
      } else if(Op==LuaVM::JSUB || Op==LuaVM::JSUB_PIC) {
        // JSUB: only imm input, rt fixed zero
        Instr.addOperand(MCOperand::createImm(imm14_sext));
      } else {
        // Standard IType: rt, rs, immediate
        Instr.addOperand(MCOperand::createReg(getRegEnc(rt)));
        Instr.addOperand(MCOperand::createReg(getRegEnc(rs)));
        Instr.addOperand(MCOperand::createImm(imm14_sext));
      }
      break;
    }

  // ========== RType format op(8),rs(5),rt(5),rd(5),pad9(0) [31-24][23-19][18-14][13-9][8-0]
  case 0x41: // ADD
  case 0x42: // SUB
  case 0x45: // MUL
  case 0x46: // DIV
  case 0x4C: // DIVu
  case 0x4D: // AND
  case 0x4E: // OR
  case 0x4F: // XOR
  case 0x51: // NOR
  case 0x52: // CMP
  case 0x53: // CMPu
  case 0x56: // SHL
  case 0x57: // SHR
  case 0x58: // SRA
  case 0x59: // SELECT
    {
      uint8_t rs = (Ins32 >> 19) & 0x1F;
      uint8_t rt = (Ins32 >> 14) & 0x1F;
      uint8_t rd = (Ins32 >> 9) & 0x1F;
      uint16_t cond9 = Ins32 & 0x1FF; // Extra 9-bit condition code for SELECT

      unsigned Op;
      switch(OpCode) {
      case 0x41: Op=LuaVM::ADD; break;
      case 0x42: Op=LuaVM::SUB; break;
      case 0x45: Op=LuaVM::MUL; break;
      case 0x46: Op=LuaVM::DIV; break;
      case 0x4C: Op=LuaVM::DIVu; break;
      case 0x4D: Op=LuaVM::AND; break;
      case 0x4E: Op=LuaVM::OR; break;
      case 0x4F: Op=LuaVM::XOR; break;
      case 0x51: Op=LuaVM::NOR; break;
      case 0x52: Op=LuaVM::CMP; break;
      case 0x53: Op=LuaVM::CMPu; break;
      case 0x56: Op=LuaVM::SHL; break;
      case 0x57: Op=LuaVM::SHR; break;
      case 0x58: Op=LuaVM::SRA; break;
      case 0x59: Op=LuaVM::SELECT; break;
      default: return MCDisassembler::Fail;
      }
      Instr.setOpcode(Op);

      if(Op == LuaVM::CMP || Op == LuaVM::CMPu) {
        // CMP/CMPu has no output register, rd fixed zero
        Instr.addOperand(MCOperand::createReg(getRegEnc(rt)));
        Instr.addOperand(MCOperand::createReg(getRegEnc(rs)));
      } else if(Op == LuaVM::SELECT) {
        // SELECT:rd, rs, rt + 9-bit condition immediate
        Instr.addOperand(MCOperand::createReg(getRegEnc(rd)));
        Instr.addOperand(MCOperand::createReg(getRegEnc(rs)));
        Instr.addOperand(MCOperand::createReg(getRegEnc(rt)));
        Instr.addOperand(MCOperand::createImm(cond9));
      } else {
        // Standard RType: output rd, input rs rt
        Instr.addOperand(MCOperand::createReg(getRegEnc(rd)));
        Instr.addOperand(MCOperand::createReg(getRegEnc(rs)));
        Instr.addOperand(MCOperand::createReg(getRegEnc(rt)));
      }
      break;
    }

  // ========== FType floating-point op(8),fs(5),ft(5),fd(5),pad9
  case 0x60: // ADDD
  case 0x61: // SUBD
  case 0x62: // MULD
  case 0x63: // DIVD
  case 0x64: // NEGD
  case 0x65: // ABSD
  case 0x66: // SQRD
  case 0x67: // CMPD
  case 0x68: // MOVD
  case 0x69: // SELECTD
    {
      uint8_t fs = (Ins32 >> 19) & 0x1F;
      uint8_t ft = (Ins32 >> 14) & 0x1F;
      uint8_t fd = (Ins32 >> 9) & 0x1F;
      uint16_t cond9 = Ins32 & 0x1FF;

      unsigned Op;
      switch(OpCode) {
      case 0x60: Op=LuaVM::ADDD; break;
      case 0x61: Op=LuaVM::SUBD; break;
      case 0x62: Op=LuaVM::MULD; break;
      case 0x63: Op=LuaVM::DIVD; break;
      case 0x64: Op=LuaVM::NEGD; break;
      case 0x65: Op=LuaVM::ABSD; break;
      case 0x66: Op=LuaVM::SQRD; break;
      case 0x67: Op=LuaVM::CMPD; break;
      case 0x68: Op=LuaVM::MOVD; break;
      case 0x69: Op=LuaVM::SELECTD; break;
      default: return MCDisassembler::Fail;
      }
      Instr.setOpcode(Op);

      // NEG/ABS/SQR/MOV use fixed zero ft field, only fd + fs
      if(Op == LuaVM::NEGD || Op == LuaVM::ABSD || Op == LuaVM::SQRD || Op == LuaVM::MOVD) {
        Instr.addOperand(MCOperand::createReg(getFPRReg(fd)));
        Instr.addOperand(MCOperand::createReg(getFPRReg(fs)));
      } else if(Op == LuaVM::SELECTD) {
        Instr.addOperand(MCOperand::createReg(getFPRReg(fd)));
        Instr.addOperand(MCOperand::createReg(getFPRReg(fs)));
        Instr.addOperand(MCOperand::createReg(getFPRReg(ft)));
        Instr.addOperand(MCOperand::createImm(cond9));
      } else if(Op == LuaVM::CMPD) {
        Instr.addOperand(MCOperand::createReg(getFPRReg(fd)));
        Instr.addOperand(MCOperand::createReg(getFPRReg(fs)));
        Instr.addOperand(MCOperand::createReg(getFPRReg(ft)));
      } else {
        // Standard floating-point arithmetic instructions
        Instr.addOperand(MCOperand::createReg(getFPRReg(fd)));
        Instr.addOperand(MCOperand::createReg(getFPRReg(fs)));
        Instr.addOperand(MCOperand::createReg(getFPRReg(ft)));
      }
      break;
    }

  // ========== MType Load/Store op(8),base(5),rt(5),offset14(14)
  case 0x01: // LD
  case 0x02: // ST
  case 0x03: // LH
  case 0x04: // SH
  case 0x05: // LB
  case 0x06: // SB
  case 0x07: // LDD
  case 0x08: // STD
  case 0x09: // LD_PIC
  case 0x0A: // ST_PIC
  case 0x0B: // LH_PIC
  case 0x0C: // SH_PIC
  case 0x0D: // LB_PIC
  case 0x0E: // SB_PIC
  case 0x0F: // LDD_PIC
  case 0x10: // STD_PIC
    {
      uint8_t base = (Ins32 >> 19) & 0x1F;
      uint8_t rt = (Ins32 >> 14) & 0x1F;
      uint16_t off14 = Ins32 & 0x3FFF;
      int64_t off_sext = SignExtend64(off14,14);

      unsigned Op;
      bool isFPR = false;
      switch(OpCode) {
      case 0x01: Op=LuaVM::LD; break;
      case 0x02: Op=LuaVM::ST; break;
      case 0x03: Op=LuaVM::LH; break;
      case 0x04: Op=LuaVM::SH; break;
      case 0x05: Op=LuaVM::LB; break;
      case 0x06: Op=LuaVM::SB; break;
      case 0x07: Op=LuaVM::LDD; isFPR=true; break;
      case 0x08: Op=LuaVM::STD; isFPR=true; break;
      case 0x09: Op=LuaVM::LD_PIC; break;
      case 0x0A: Op=LuaVM::ST_PIC; break;
      case 0x0B: Op=LuaVM::LH_PIC; break;
      case 0x0C: Op=LuaVM::SH_PIC; break;
      case 0x0D: Op=LuaVM::LB_PIC; break;
      case 0x0E: Op=LuaVM::SB_PIC; break;
      case 0x0F: Op=LuaVM::LDD_PIC; isFPR=true; break;
      case 0x10: Op=LuaVM::STD_PIC; isFPR=true; break;
      default: return MCDisassembler::Fail;
      }
      Instr.setOpcode(Op);

      // Store: rt, base, offset | Load: rt(output), base, offset(input)
      if(Op==LuaVM::ST || Op==LuaVM::SH || Op==LuaVM::SB ||
         Op==LuaVM::ST_PIC || Op==LuaVM::SH_PIC || Op==LuaVM::SB_PIC ||
         Op==LuaVM::STD || Op==LuaVM::STD_PIC) {
        unsigned RtReg = isFPR ? getFPRReg(rt) : getRegEnc(rt);
        Instr.addOperand(MCOperand::createReg(RtReg));
        Instr.addOperand(MCOperand::createReg(getRegEnc(base)));
        Instr.addOperand(MCOperand::createImm(off_sext));
      } else {
        unsigned RtReg = isFPR ? getFPRReg(rt) : getRegEnc(rt);
        Instr.addOperand(MCOperand::createReg(RtReg));
        Instr.addOperand(MCOperand::createReg(getRegEnc(base)));
        Instr.addOperand(MCOperand::createImm(off_sext));
      }
      break;
    }

  // ========== JType branch op(8),addr24(24) [31-24][23:0]
  case 0x80: // JEQ
  case 0x81: // JNE
  case 0x82: // JLT
  case 0x83: // JGT
  case 0x84: // JLE
  case 0x85: // JGE
  case 0x86: // JMP
  case 0x89: // RET
    {
      uint32_t addr24 = Ins32 & 0xFFFFFF;
      unsigned Op;
      switch(OpCode) {
      case 0x80: Op=LuaVM::JEQ; break;
      case 0x81: Op=LuaVM::JNE; break;
      case 0x82: Op=LuaVM::JLT; break;
      case 0x83: Op=LuaVM::JGT; break;
      case 0x84: Op=LuaVM::JLE; break;
      case 0x85: Op=LuaVM::JGE; break;
      case 0x86: Op=LuaVM::JMP; break;
      case 0x89: Op=LuaVM::RET; break;
      default: return MCDisassembler::Fail;
      }
      Instr.setOpcode(Op);
      if(Op != LuaVM::RET) {
        // Jxx/JMP takes 24-bit target address immediate
        Instr.addOperand(MCOperand::createImm(addr24));
      }
      break;
    }

  default:
    // Unknown opcode, decode failed
    Size=0;
    return MCDisassembler::Fail;
  }

  return MCDisassembler::Success;
}

// Map hardware encoding to LLVM GPR register enum: r0~r12 + SP/FP/LINK/PDC0/PDC1/HI/LO/STR
unsigned LuaVMDisassembler::getRegEnc(uint8_t HWEnc) const {
  // TD defined mapping: R0-R12=0~12; FP=13,SP=14,LINK=15,PDC0=16,PDC1=17
  switch(HWEnc) {
  case 0: return LuaVM::R0; case 1: return LuaVM::R1; case 2: return LuaVM::R2;
  case 3: return LuaVM::R3; case 4: return LuaVM::R4; case 5: return LuaVM::R5;
  case 6: return LuaVM::R6; case 7: return LuaVM::R7; case 8: return LuaVM::R8;
  case 9: return LuaVM::R9; case 10: return LuaVM::R10;case 11: return LuaVM::R11;
  case 12: return LuaVM::R12;case 13: return LuaVM::FP; case 14: return LuaVM::SP;
  case 15: return LuaVM::LINK;case 16: return LuaVM::PDC0;case 17: return LuaVM::PDC1;
  default: return 0;
  }
}

// Map hardware encoding to FPR floating-point register F0~F31
unsigned LuaVMDisassembler::getFPRReg(uint8_t HWEnc) const{
  switch (HWEnc) {
#define F_CASE(n) case n: return LuaVM::F##n
  F_CASE(0);F_CASE(1);F_CASE(2);F_CASE(3);F_CASE(4);F_CASE(5);F_CASE(6);F_CASE(7);
  F_CASE(8);F_CASE(9);F_CASE(10);F_CASE(11);F_CASE(12);F_CASE(13);F_CASE(14);F_CASE(15);
  F_CASE(16);F_CASE(17);F_CASE(18);F_CASE(19);F_CASE(20);F_CASE(21);F_CASE(22);F_CASE(23);
  F_CASE(24);F_CASE(25);F_CASE(26);F_CASE(27);F_CASE(28);F_CASE(29);F_CASE(30);F_CASE(31);
#undef F_CASE
  default: return 0;
  }
}