#include "llvm/Support/FormattedStream.h"

using namespace llvm;

LuaVMInstPrinter::LuaVMInstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                                   const MCRegisterInfo &MRI)
    : MCInstPrinter(MAI, MII, MRI) {}

void LuaVMInstPrinter::printRegName(raw_ostream &OS, unsigned RegNo) const {
  // Print the register name based on its number.
  // This uses the register names defined in the .td file.
  // `getRegisterName` is auto-generated by TableGen.
  OS << '$' << StringRef(getRegisterName(RegNo)).lower();
}

void LuaVMInstPrinter::printInst(const MCInst *MI, raw_ostream &O, StringRef Annot,
                                 const MCSubtargetInfo &STI) {
  // Print the instruction mnemonic.
  O << '\t' << getInstrInfo()->getName(MI->getOpcode());

  // Print operands, separated by commas.
  if (MI->getNumOperands() > 0) {
    O << '\t';
    for (unsigned i = 0; i < MI->getNumOperands(); ++i) {
      if (i != 0) O << ", ";
      printOperand(MI, i, O);
    }
  }

  // Print any annotation.
  if (!Annot.empty()) {
    O << "\t# " << Annot;
  }
}

void LuaVMInstPrinter::printOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O) const {
  const MCOperand &Op = MI->getOperand(OpNo);
  if (Op.isReg()) {
    printRegName(O, Op.getReg());
  } else if (Op.isImm()) {
    O << Op.getImm();
  } else if (Op.isExpr()) {
    // Handle expressions (e.g., labels, offsets).
    // This is a complex topic. For now, just print the expression.
    Op.getExpr()->print(O, &MAI);
  } else {
    llvm_unreachable("Unhandled operand type!");
  }
}